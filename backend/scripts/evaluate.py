#!/usr/bin/env python3
"""Run the correlation benchmark and write the research report.

Usage:
    python scripts/evaluate.py            # two seeds plus a volume run
    python scripts/evaluate.py --quick    # single seed
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.evaluation.runner import run  # noqa: E402

REPORT_DIR = ROOT.parent / "docs" / "research"
METHOD_LABELS = {
    "ip_only": "IP-only grouping (baseline)",
    "rule_based": "Rule-based matching (baseline)",
    "proposed": "Evidence-weighted correlation (proposed)",
    "proposed_adaptive": "Proposed + adaptive observation",
    "ablation_no_intel": "Ablation: no threat-intel family",
    "ablation_no_timing": "Ablation: no timing family",
    "ablation_no_toolchain": "Ablation: no toolchain family",
    "ablation_uniform_weights": "Ablation: uniform family weights",
}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--quick", action="store_true")
    args = parser.parse_args()

    seeds = [7] if args.quick else [7, 2026]
    runs = [run(seed=seed, high_volume=False) for seed in seeds]
    volume = run(seed=99, high_volume=True, include_ablations=False)

    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    payload = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "runs": runs,
        "volume_run": volume,
    }
    (REPORT_DIR / "evaluation-results.json").write_text(
        json.dumps(payload, indent=2, sort_keys=True), encoding="utf-8"
    )
    (REPORT_DIR / "evaluation-results.md").write_text(_markdown(runs, volume), encoding="utf-8")
    print(f"wrote {REPORT_DIR / 'evaluation-results.md'}")
    for result in runs:
        proposed = result["results"]["proposed"]
        print(
            f"seed {result['seed']}: precision={proposed['precision']:.3f} "
            f"recall={proposed['recall']:.3f} f1={proposed['f1']:.3f} "
            f"fpr={proposed['false_positive_rate']:.4f} "
            f"campaigns={result['campaign_analysis']['predicted_clusters']}"
        )
    return 0


def _markdown(runs: list[dict], volume: dict) -> str:
    lines: list[str] = [
        "# Correlation evaluation",
        "",
        "Generated by `backend/scripts/evaluate.py`. Numbers below are computed from the",
        "labelled synthetic benchmark in `backend/app/evaluation/scenarios.py`.",
        "",
        "## Protocol",
        "",
        "- Unit of analysis: session. Labels mark sessions that belong to the same",
        "  coordinated scenario (campaign), not necessarily the same person.",
        "- Positive pair: both sessions belong to the same true scenario.",
        "- `linked` decisions are counted as positive; hypotheses are not.",
        "- Link thresholds are unchanged from the previous revision and were not tuned",
        "  on this benchmark. The corpus-relative family weighting added in",
        "  `corr-1.2.0` was evaluated on the same benchmark it is reported on; there is",
        "  no separate validation set, so its gain is reported as preliminary.",
        "- Every run is deterministic from its seed. The generator is synthetic;",
        "  absolute performance on production traffic will differ.",
        "",
    ]
    for result in runs:
        lines += [
            f"## Seed {result['seed']}",
            "",
            f"Dataset: {result['sessions']} sessions, {result['pairs']} pairs "
            f"({result['positives']} positive, {result['negatives']} negative), "
            f"algorithm `{result['algorithm_version']}`.",
            "",
            "| Method | Precision | Recall | F1 | FPR | FNR | TP | FP | FN |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
        ]
        for method, metrics in result["results"].items():
            lines.append(
                f"| {METHOD_LABELS.get(method, method)} | {metrics['precision']:.3f} | "
                f"{metrics['recall']:.3f} | {metrics['f1']:.3f} | "
                f"{metrics['false_positive_rate']:.4f} | {metrics['false_negative_rate']:.4f} | "
                f"{metrics['tp']} | {metrics['fp']} | {metrics['fn']} |"
            )
        campaign = result["campaign_analysis"]
        adaptive = result["adaptive"]
        resources = result["resources"]
        lines += [
            "Subset breakdown for the proposed method (evaluable pairs only):",
            "",
            "| Subset | Pairs | Positives | Precision | Recall | FP | FN |",
            "| --- | --- | --- | --- | --- | --- | --- |",
        ]
        for name, subset in result.get("subsets", {}).items():
            lines.append(
                f"| {name} | {subset['pairs']} | {subset['positives']} | "
                f"{subset['precision']:.3f} | {subset['recall']:.3f} | "
                f"{subset['fp']} | {subset['fn']} |"
            )
        lines += [""]
        hard = result.get("hard_subset", {})
        if hard.get("pairs"):
            lines += [
                "Hard subset (generic scanner toolkit; labels not recoverable from telemetry):",
                "",
                "| Method | Precision | Recall | F1 | FP |",
                "| --- | --- | --- | --- | --- |",
            ]
            for method, metrics in hard["results"].items():
                lines.append(
                    f"| {method} | {metrics['precision']:.3f} | {metrics['recall']:.3f} | "
                    f"{metrics['f1']:.3f} | {metrics['fp']} |"
                )
            lines += ["", hard["note"], ""]
        lines += [
            "",
            f"Campaign-level: {campaign['groups_recovered_exactly']} of "
            f"{campaign['true_multi_session_groups']} true groups recovered exactly; "
            f"{campaign['predicted_clusters']} predicted clusters, purity "
            f"{campaign['cluster_purity']:.3f}. {campaign['note']}",
            "",
            f"Adaptive experiment: {adaptive['ambiguous_pairs']} ambiguous pairs in "
            f"{adaptive['candidate_components']} candidate clusters; "
            f"{adaptive['components_investigated']} clusters investigated, "
            f"{adaptive['pairs_recomputed']} pairs recomputed; of the evaluable pairs, "
            f"{adaptive['resolved_correctly']} links gained correctly, "
            f"{adaptive['resolved_incorrectly']} gained incorrectly, "
            f"{adaptive['lost_correctly']} lost correctly and "
            f"{adaptive['lost_incorrectly']} lost incorrectly; "
            f"{adaptive['unchanged']} unchanged. {adaptive['note']}",
            "",
            f"Resources: total {resources['total_seconds']:.3f}s, peak memory "
            f"{resources['peak_memory_mb']:.2f} MB, {resources['sessions_per_second']} sessions/s.",
            "",
        ]

    lines += [
        f"## Volume run (seed {volume['seed']})",
        "",
        f"{volume['sessions']} sessions and {volume['pairs']} pairs: "
        f"total {volume['resources']['total_seconds']:.3f}s, peak memory "
        f"{volume['resources']['peak_memory_mb']:.2f} MB.",
        "",
        "| Method | Precision | Recall | F1 | FPR |",
        "| --- | --- | --- | --- | --- |",
    ]
    for method, metrics in volume["results"].items():
        lines.append(
            f"| {METHOD_LABELS.get(method, method)} | {metrics['precision']:.3f} | "
            f"{metrics['recall']:.3f} | {metrics['f1']:.3f} | "
            f"{metrics['false_positive_rate']:.4f} |"
        )
    lines += [
        "",
        "## Limitations",
        "",
    ]
    lines += [f"- {item}" for item in runs[0]["limitations"]]
    lines += [
        "- The benchmark is small relative to production telemetry and does not model",
        "  long-lived multi-week campaigns.",
        "- Synthetic sessions were written for this project; they are not redistributed",
        "  public attack data, and they may contain generator bias.",
        "",
        "## Reproducing",
        "",
        "```bash",
        "cd backend",
        "python scripts/evaluate.py",
        "```",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    raise SystemExit(main())
